/* Crownly web daily: today's normal daily Queens puzzle (the same board as the app).
   Puzzles are pre-generated by `puzzlecli webdaily` into /crownly/daily/<yyyy-MM-dd>.json (regions only).
   A puzzle day starts at 07:00 UTC for everyone, exactly like PuzzleDay in the app. */
(function () {
  "use strict";
  var C = window.CROWNLY_PLAY, T = C.t;
  var FILLS = ["#CDBEEB", "#F6CFA8", "#B9D3F2", "#C5E0B5", "#F2B8C6", "#F1E6A6", "#B2E0D6", "#DCD6CC", "#F3A99B", "#D9BC98"];
  var DOTS = ["#7A62B4", "#C27E43", "#5486C4", "#66934C", "#BE5876", "#A48F2C", "#47977F", "#857C6B", "#BF5343", "#96693C"];
  // The app's default board crown ("Crownly" style: pastel patchwork, gold outline, plum ring); Crownly/Tools/web_crown.swift.
  var CROWN = '<img src="/crownly/img/board-crown.png" alt="" draggable="false">';
  new Image().src = "/crownly/img/board-crown.png";  // preload, so the first crown appears at once

  var $ = function (id) { return document.getElementById(id); };
  var root = $("cq"), boardEl = $("cq-board"), timeEl = $("cq-time"), dateEl = $("cq-date"), statusEl = $("cq-status");
  var dayIndex = Math.floor((Date.now() / 1000 - 25200) / 86400);
  var iso = new Date(dayIndex * 86400000).toISOString().slice(0, 10);
  var key = "crownly-web-" + iso;
  var n = 0, regions = [], marks = [], history = [], cells = [];
  var elapsed = 0, runningSince = 0, solved = false, ticker = 0;

  dateEl.textContent = new Intl.DateTimeFormat(C.lang, { day: "numeric", month: "long", timeZone: "UTC" })
    .format(new Date(dayIndex * 86400000));

  function store(read, value) {
    try {
      if (read) return JSON.parse(localStorage.getItem(key) || "null");
      localStorage.setItem(key, JSON.stringify(value));
    } catch (e) { return null; }
  }
  function save() { store(false, { marks: marks, elapsed: currentSeconds(), solved: solved }); }

  function fmt(s) { s = Math.floor(s); return Math.floor(s / 60) + ":" + String(s % 60).padStart(2, "0"); }
  function currentSeconds() { return elapsed + (runningSince ? (performance.now() - runningSince) / 1000 : 0); }
  function tick() { timeEl.textContent = fmt(currentSeconds()); }
  function startClock() {
    if (solved || runningSince || document.hidden) return;
    runningSince = performance.now();
    ticker = setInterval(tick, 250);
  }
  function stopClock() {
    if (!runningSince) return;
    elapsed = currentSeconds(); runningSince = 0; clearInterval(ticker); tick();
  }
  var started = false;
  document.addEventListener("visibilitychange", function () {
    if (document.hidden) { stopClock(); save(); } else if (started) startClock();
  });

  function build() {
    boardEl.style.setProperty("--n", n);
    boardEl.innerHTML = "";
    cells = [];
    for (var i = 0; i < n * n; i++) {
      var r = Math.floor(i / n), c = i % n, g = regions[i], el = document.createElement("div");
      el.className = "cq-cell";
      if (r === 0 || regions[i - n] !== g) el.classList.add("et");
      if (r === n - 1 || regions[i + n] !== g) el.classList.add("eb");
      if (c === 0 || regions[i - 1] !== g) el.classList.add("el");
      if (c === n - 1 || regions[i + 1] !== g) el.classList.add("er");
      el.style.background = FILLS[g % 10];
      el.style.setProperty("--dot", DOTS[g % 10]);
      el.dataset.i = i;
      el.setAttribute("role", "gridcell");
      el.tabIndex = i === 0 ? 0 : -1;
      boardEl.appendChild(el);
      cells.push(el);
    }
  }

  function conflicts() {
    var bad = {}, crowns = [];
    for (var i = 0; i < marks.length; i++) if (marks[i] === 2) crowns.push(i);
    for (var a = 0; a < crowns.length; a++) for (var b = a + 1; b < crowns.length; b++) {
      var p = crowns[a], q = crowns[b], pr = Math.floor(p / n), pc = p % n, qr = Math.floor(q / n), qc = q % n;
      if (pr === qr || pc === qc || regions[p] === regions[q] || (Math.abs(pr - qr) <= 1 && Math.abs(pc - qc) <= 1)) {
        bad[p] = true; bad[q] = true;
      }
    }
    return { bad: bad, count: crowns.length };
  }

  function label(i) {
    var what = marks[i] === 2 ? T.crown : marks[i] === 1 ? T.dot : T.empty;
    return T.cell.replace("{r}", Math.floor(i / n) + 1).replace("{c}", i % n + 1) + ", " + what;
  }

  function render() {
    var k = conflicts();
    for (var i = 0; i < cells.length; i++) {
      var el = cells[i], m = marks[i];
      el.innerHTML = m === 2 ? '<span class="cq-crown">' + CROWN + "</span>" : m === 1 ? '<span class="cq-dot"></span>' : "";
      el.classList.toggle("bad", !!k.bad[i]);
      el.setAttribute("aria-label", label(i));
    }
    $("cq-count").textContent = T.left.replace("{n}", Math.max(0, n - k.count));
    $("cq-undo").disabled = history.length === 0 || solved;
    $("cq-clear").disabled = solved || marks.every(function (m) { return m === 0; });
    if (!solved && k.count === n && Object.keys(k.bad).length === 0) win(true);
  }

  function change(next) {
    if (solved) return;
    history.push(marks.slice());
    if (history.length > 200) history.shift();
    marks = next;
    started = true; startClock();
    render();
    save();
  }

  function setMark(i, value) { var next = marks.slice(); next[i] = value; change(next); }
  function cycle(i) { setMark(i, (marks[i] + 1) % 3); }

  // Tap: empty → dot → crown → empty. Drag from a cell: dots on every empty cell the finger passes.
  var drag = null;
  function cellAt(x, y) {
    var el = document.elementFromPoint(x, y);
    while (el && el !== boardEl && !(el.dataset && el.dataset.i)) el = el.parentElement;
    return el && el.dataset && el.dataset.i ? +el.dataset.i : -1;
  }
  boardEl.addEventListener("pointerdown", function (e) {
    if (solved) return;
    var i = cellAt(e.clientX, e.clientY);
    if (i < 0) return;
    e.preventDefault();
    boardEl.setPointerCapture(e.pointerId);
    drag = { start: i, last: i, moved: false, painted: null };
  });
  boardEl.addEventListener("pointermove", function (e) {
    if (!drag) return;
    var i = cellAt(e.clientX, e.clientY);
    if (i < 0 || i === drag.last) return;
    if (!drag.moved) {
      drag.moved = true;
      drag.painted = marks.slice();
      if (drag.painted[drag.start] === 0) drag.painted[drag.start] = 1;
      history.push(marks.slice());
    }
    if (drag.painted[i] === 0) drag.painted[i] = 1;
    drag.last = i;
    marks = drag.painted.slice();
    started = true; startClock();
    render();
  });
  function endDrag() {
    if (!drag) return;
    var d = drag; drag = null;
    if (d.moved) save(); else cycle(d.start);
  }
  boardEl.addEventListener("pointerup", endDrag);
  boardEl.addEventListener("pointercancel", function () { if (drag && drag.moved) save(); drag = null; });

  // Keyboard: arrows move, Space/Enter cycles.
  boardEl.addEventListener("keydown", function (e) {
    var i = +(document.activeElement.dataset.i || 0), r = Math.floor(i / n), c = i % n, j = i;
    if (e.key === "ArrowUp") j = Math.max(0, r - 1) * n + c;
    else if (e.key === "ArrowDown") j = Math.min(n - 1, r + 1) * n + c;
    else if (e.key === "ArrowLeft") j = r * n + Math.max(0, c - 1);
    else if (e.key === "ArrowRight") j = r * n + Math.min(n - 1, c + 1);
    else if (e.key === " " || e.key === "Enter") { e.preventDefault(); cycle(i); return; }
    else return;
    e.preventDefault();
    cells[i].tabIndex = -1; cells[j].tabIndex = 0; cells[j].focus();
  });

  $("cq-undo").addEventListener("click", function () {
    if (!history.length || solved) return;
    marks = history.pop(); render(); save();
  });
  $("cq-clear").addEventListener("click", function () {
    if (solved || marks.every(function (m) { return m === 0; })) return;
    change(marks.map(function () { return 0; }));
  });

  function countdown() {
    var next = ((dayIndex + 1) * 86400 + 25200) * 1000, left = Math.max(0, Math.floor((next - Date.now()) / 1000));
    var h = Math.floor(left / 3600), m = Math.floor(left % 3600 / 60), s = left % 60;
    $("cq-next").textContent = T.next.replace("{t}", h + ":" + String(m).padStart(2, "0") + ":" + String(s).padStart(2, "0"));
    if (left === 0) { $("cq-next").textContent = T.ready; return; }
    setTimeout(countdown, 1000);
  }

  function shareText() {
    return "Crownly · " + dateEl.textContent + " 👑 " + fmt(elapsed) + "\n" + C.url;
  }

  function win(fresh) {
    solved = true;
    stopClock();
    if (fresh) save();
    root.classList.add("solved");
    $("cq-result-time").textContent = fmt(elapsed);
    $("cq-result").hidden = false;
    statusEl.textContent = T.solved.replace("{t}", fmt(elapsed));
    $("cq-undo").disabled = true; $("cq-clear").disabled = true;
    countdown();
  }

  $("cq-share").addEventListener("click", function () {
    var text = shareText(), btn = this;
    if (navigator.share) { navigator.share({ text: text }).catch(function () {}); return; }
    var done = function () { btn.textContent = T.copied; setTimeout(function () { btn.textContent = T.share; }, 1800); };
    if (navigator.clipboard) navigator.clipboard.writeText(text).then(done, function () {});
  });

  fetch("/crownly/daily/" + iso + ".json", { cache: "no-cache" })
    .then(function (r) { if (!r.ok) throw new Error(r.status); return r.json(); })
    .then(function (p) {
      n = p.size;
      regions = p.regions.split("").map(Number);
      var saved = store(true);
      marks = saved && saved.marks && saved.marks.length === n * n ? saved.marks : regions.map(function () { return 0; });
      elapsed = saved ? saved.elapsed || 0 : 0;
      build();
      root.classList.remove("loading");
      tick();
      render();
      if (saved && saved.solved) win(false);
      else if (elapsed > 0) started = true;
    })
    .catch(function () {
      root.classList.remove("loading");
      statusEl.textContent = T.error;
    });
})();
